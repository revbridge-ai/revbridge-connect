#!/usr/bin/env python3
"""Renders the MTA configuration (Postfix, OpenDKIM, Dovecot, rsyslog) from mta/templates
with the container's environment variables.

Usage: render.py <templates_root>

Every variable comes from the environment (the .env generated by `make env`); no password is
stored in the image. Missing required variables stop the boot with an error.
"""

import os
import sys

from jinja2 import Environment, FileSystemLoader, StrictUndefined

# (template relative to templates_root, destination, mode)
MANIFEST = [
    ("opendkim/opendkim.conf", "/etc/opendkim.conf", 0o644),
    ("opendkim/opendkim/TrustedHosts", "/etc/opendkim/TrustedHosts", 0o644),
    ("opendkim/opendkim/lua/keytable.lua", "/etc/opendkim/lua/keytable.lua", 0o644),
    ("opendkim/opendkim/lua/signingtable.lua", "/etc/opendkim/lua/signingtable.lua", 0o644),
    ("postfix/main.cf", "/etc/postfix/main.cf", 0o644),
    ("postfix/master.cf", "/etc/postfix/master.cf", 0o644),
    ("postfix/mysql-virtual-alias-maps.cf", "/etc/postfix/mysql-virtual-alias-maps.cf", 0o640),
    ("postfix/mysql-virtual-alias-domains.cf", "/etc/postfix/mysql-virtual-alias-domains.cf", 0o640),
    ("postfix/mysql-virtual-mailbox-domains.cf", "/etc/postfix/mysql-virtual-mailbox-domains.cf", 0o640),
    ("postfix/mysql-virtual-mailbox-maps.cf", "/etc/postfix/mysql-virtual-mailbox-maps.cf", 0o640),
    ("postfix/transport", "/etc/postfix/transport", 0o644),
    ("postfix/bounce_accept.regexp", "/etc/postfix/bounce_accept.regexp", 0o644),
    ("postfix/bounce_transport.regexp", "/etc/postfix/bounce_transport.regexp", 0o644),
    ("postfix/sender_canonical", "/etc/postfix/sender_canonical", 0o644),
    ("postfix/forward_async_bounce.sh.j2", "/usr/local/bin/forward_async_bounce.sh", 0o755),
    ("dovecot/dovecot.conf", "/etc/dovecot/dovecot.conf", 0o644),
    ("dovecot/dovecot-sql.conf.ext", "/etc/dovecot/dovecot-sql.conf.ext", 0o600),
    ("dovecot/dovecot-sql-api-keys.conf.ext", "/etc/dovecot/dovecot-sql-api-keys.conf.ext", 0o600),
    ("dovecot/conf.d/auth-sql.conf.ext", "/etc/dovecot/conf.d/auth-sql.conf.ext", 0o644),
    ("dovecot/conf.d/10-auth.conf", "/etc/dovecot/conf.d/10-auth.conf", 0o644),
    ("dovecot/conf.d/10-logging.conf", "/etc/dovecot/conf.d/10-logging.conf", 0o644),
    ("dovecot/conf.d/10-mail.conf", "/etc/dovecot/conf.d/10-mail.conf", 0o644),
    ("dovecot/conf.d/10-master.conf", "/etc/dovecot/conf.d/10-master.conf", 0o644),
    ("dovecot/conf.d/10-ssl.conf", "/etc/dovecot/conf.d/10-ssl.conf", 0o644),
    ("rsyslog.d/mail.conf", "/etc/rsyslog.d/mail.conf", 0o644),
]

# template variable -> (environment variable, default; None = required)
CONTEXT = {
    "domain": ("DOMAIN", None),
    "myhostname": ("MYHOSTNAME", None),
    "mailbox_user": ("MAILBOX_USER", None),
    "mailbox_password": ("MAILBOX_PASSWORD", None),
    "mysql_host": ("MYSQL_HOST", "db"),
    "mysql_port": ("MYSQL_PORT", "3306"),
    "mysql_database": ("MYSQL_DATABASE", "revbridge_connect"),
    "milter_host": ("MILTER_HOST", "milter"),
    "events_updater_host": ("EVENTS_UPDATER_HOST", "events"),
    "relayhost": ("RELAYHOST", ""),
    "queue_submission_port": ("QUEUE_SUBMISSION_PORT", "2587"),
    "queue_submission_maxproc": ("QUEUE_SUBMISSION_MAXPROC", "64"),
    "anvil_conn_rate": ("SMTP_CONN_RATE_LIMIT", "60"),
    "anvil_conn_count": ("SMTP_CONN_COUNT_LIMIT", "20"),
    "anvil_msg_rate": ("SMTP_MSG_RATE_LIMIT", "600"),
    "anvil_auth_rate": ("SMTP_AUTH_RATE_LIMIT", "30"),
}


def main() -> int:
    if len(sys.argv) != 2:
        sys.exit("usage: render.py <templates_root>")
    root = sys.argv[1]
    ctx, missing = {}, []
    for var, (env_key, default) in CONTEXT.items():
        value = os.environ.get(env_key, default)
        if value is None or value == "" and default is None:
            missing.append(env_key)
        ctx[var] = value
    if missing:
        sys.exit(f"render: missing required variables: {', '.join(missing)}")

    env = Environment(loader=FileSystemLoader(root), keep_trailing_newline=True, undefined=StrictUndefined)
    for src, dest, mode in MANIFEST:
        rendered = env.get_template(src).render(**ctx)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as out:
            out.write(rendered)
        os.chmod(dest, mode)
    print(f"render: {len(MANIFEST)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
