"""Generates/updates the variable catalog (config/variables.toml) from the code.

Scans services/, shared/, libs/ and mta/ for environment reads
(os.getenv, os.environ, BaseSettings, ${VAR:-default} in shell/Dockerfile),
classifies each variable with the rules below and keeps what was already curated
by hand in the catalog (fields `status`, `value`, `note`, `group`, `curated = true`).

Usage:
  python3 tools/manifest/scan_env.py                 # updates config/variables.toml
  python3 tools/manifest/scan_env.py --check         # fails if the code reads a variable missing from the catalog

Standard library only (Python >= 3.11).
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import sys
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CATALOG = os.path.join(ROOT, "config", "variables.toml")
# Hand curation: wins over the rules and the inherited defaults. Every entry that deviates from them has `deviation`.
OVERRIDES = os.path.join(ROOT, "config", "variables.overrides.toml")
SCAN_DIRS = ["services", "shared", "libs", "mta"]
SKIP_DIRS = {"tests", "__pycache__", ".venv", "node_modules", "build", "dist"}

# Order matters: the first matching rule decides group, status and note.
# status: derive (comes from connect.toml) | keep (code default) | secret (generated by make env)
#         off (code present, turned off in Connect) | remove (to be removed from the code) | internal (not configurable)
#         review (not classified yet)
RULES: list[tuple[str, str, str, str]] = [
    (r"^KAFKA_", "events", "off", "not used; events go out through webhooks"),
    (r"^DD_", "observability", "off", "not used; metrics through Prometheus, OTel optional"),
    (r"^OTEL_", "observability", "keep", "OpenTelemetry optional (off by default)"),
    (r"^(IMAGE_PROXY_|GEO_SERVICE_)", "integrations", "off", "optional; see config/variables.overrides.toml"),
    (r"^(SPAMHAUS_)", "deliverability", "keep", "optional: Spamhaus DQS key (commercial use)"),
    (r"^(VR|IW|EC|WC|HEALTH|TC|RF|DS|SPFA|AUDIT|REPUTATION|DEFERRAL|REFILL|RC|FS)_", "deliverability", "keep", "deliverability job; inherited default"),
    (r"^(VOLUME_|SUPPRESSION_|QUEUE_FAIRNESS|OPEN_MIN_DELTA|WARMUP_|EGRESS_|RL_|LEDGER_|SEND_LEDGER_|DEFERRED|BOUNCE_LIFETIME$|MAX_LIFETIME$|RECOVERY_CLEAN_HOURS$|WORKER_REQUEUE_DEFERRED$)", "sending", "keep", "sending/deliverability; inherited default"),
    (r"^(JWT_SECRET_KEY|TOKEN_ENCRYPTION_KEY|SMTP_PASSWORD|MAILBOX_PASSWORD|DB_PASSWORD|REDIS_PASSWORD|SSH_PRIVATE_KEY|SPAMHAUS_DQS_KEY)$", "secrets", "secret", "generated by make env (secrets/, outside git)"),
    (r"^(DB_|MYSQL_|MAIL_DB_NAME$|MAILBOX_USER$)", "database", "derive", "the installation's MySQL"),
    (r"^(REDIS_|AUTH_CACHE_REDIS_URL$)", "redis", "derive", "the installation's Redis"),
    (r"^(MYHOSTNAME|HOSTNAME|MESSAGE_ID_DOMAIN|TRACK_BASE|SUBMISSION_HOST|RELAY_HOST|RELAY_PORT|EVENTS_UPDATER_HOST|EVENTS_UPDATER_PORT|TRACKER_HOST|TRACKER_PORT|API_SERVICE_HOST|API_SERVICE_PORT|MAIL_URL|MAIL_INFRA_SERVICE_URL|DOMAIN|SUBDOMAIN_LB|INTERNAL_INJECT_PORT|PROXY_PROTOCOL_PORTS)$", "endpoints", "derive", "the installation's addresses"),
    (r"^(ANSIBLE_|SSH_PUBLIC_KEY$)", "nodes", "keep", "node provisioning over SSH"),
    (r"^(DKIM_|RELAY_DB_ROUTING$)", "mta", "keep", "MTA"),
    (r"^(SMTP_|SUBMISSION_|DISABLE_SUBMISSION_PROXY$)", "mta", "keep", "SMTP"),
    (r"^(AUTH_|API_KEY_|JWT_|RATE_LIMIT_)", "auth", "keep", "API authentication/limits"),
    (r"^(WEBHOOK_)", "events", "keep", "event webhooks"),
    (r"^(LOG_|DEBUG_|SERVICE_NAME$|PORT$|HOST$|ENV$|ENVIRONMENT$|MALLOC_|API_HOST$|API_PORT$|HTTP_)", "runtime", "keep", "runtime"),
    (r"^(EMAIL_|INGEST_EXECUTOR_WORKERS$|INJECT_PIXEL$|REWRITE_LINKS$|OUTBOX_)", "sending", "keep", "queue/milter; code default"),
    (r"^(CLAIM_|DEFAULT_CLAIM_PROVIDER$|DEPLOYMENT_|RELAY_DEFAULT_DAILY_CAP$)", "nodes", "keep", "zone/node infrastructure; code default"),
    (r"^(TS|TO|FROM|FROM_DOMAIN|SENT|REFUSED|GROUP|IP|EXIT_CODE|MODE|KEY_DIR|SCRIPT_DIR|BASE_DIR|PATH|HOME|DEBIAN_FRONTEND|TASK_TYPE|TARGET_SCHEMA|TEST_DOMAIN_ID|CUSTOMERS_PAYLOAD|CUSTOM_SQL_LIST|SERVER_TYPE|VERBOSITY|PROJECT|ZONE_IDENTIFIER|CUSTOMER|CUSTOMER_NAME|DOMAIN_NAME|APPLY|SHADOW_EMAIL)$", "internal", "internal", "local script/test variable; not configuration"),
]


def classify(name: str) -> tuple[str, str, str]:
    for rx, group, status, note in RULES:
        if re.search(rx, name):
            return group, status, note
    return "misc", "review", ""


def lit(node):
    try:
        return ast.literal_eval(node)
    except Exception:
        return None


def service_of(rel: str) -> str:
    parts = rel.split(os.sep)
    if parts[0] == "services" and len(parts) > 1:
        return parts[1]
    if parts[0] == "libs":
        return "lib"
    return parts[0]


def scan() -> dict[str, dict]:
    found: dict[str, dict] = {}

    def add(name, default, rel):
        if not isinstance(name, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]{1,80}", name):
            return
        e = found.setdefault(name, {"defaults": set(), "services": set(), "files": set()})
        if default is not None and not isinstance(default, (dict, list)):
            e["defaults"].add(str(default))
        e["services"].add(service_of(rel))
        e["files"].add(rel)

    class V(ast.NodeVisitor):
        def __init__(self, rel):
            self.rel = rel

        def visit_Call(self, node):
            fn = ast.unparse(node.func)
            if fn in ("os.getenv", "getenv", "os.environ.get", "environ.get") and node.args:
                add(lit(node.args[0]), lit(node.args[1]) if len(node.args) > 1 else None, self.rel)
            elif (fn.endswith("_env") or fn.endswith("env_bool") or fn.endswith("env_int")
                  or fn in ("_bool", "_int", "_float", "_str", "env_flag")) and node.args:
                add(lit(node.args[0]), lit(node.args[1]) if len(node.args) > 1 else None, self.rel)
            self.generic_visit(node)

        def visit_Subscript(self, node):
            if ast.unparse(node.value) in ("os.environ", "environ"):
                add(lit(node.slice), None, self.rel)
            self.generic_visit(node)

        def visit_ClassDef(self, node):
            if any("BaseSettings" in ast.unparse(b) for b in node.bases):
                prefix = ""
                for st in node.body:
                    if isinstance(st, ast.Assign) and isinstance(st.value, ast.Call):
                        for kw in st.value.keywords:
                            if kw.arg == "env_prefix":
                                prefix = lit(kw.value) or ""
                for st in node.body:
                    if isinstance(st, ast.AnnAssign) and isinstance(st.target, ast.Name):
                        default, alias = None, None
                        if isinstance(st.value, ast.Call) and ast.unparse(st.value.func).endswith("Field"):
                            if st.value.args:
                                default = lit(st.value.args[0])
                            for kw in st.value.keywords:
                                if kw.arg == "default":
                                    default = lit(kw.value)
                                if kw.arg in ("alias", "validation_alias", "env"):
                                    alias = lit(kw.value)
                        elif st.value is not None:
                            default = lit(st.value)
                        add(alias if isinstance(alias, str) else (prefix + st.target.id).upper(), default, self.rel)
            self.generic_visit(node)

    shell_re = re.compile(r"\$\{([A-Z][A-Z0-9_]+)(?::?[-=]([^}]*))?\}")
    for base in SCAN_DIRS:
        top = os.path.join(ROOT, base)
        for dp, dns, fns in os.walk(top):
            dns[:] = [d for d in dns if d not in SKIP_DIRS]
            for fn in fns:
                path = os.path.join(dp, fn)
                rel = os.path.relpath(path, ROOT)
                if fn.endswith(".py") and not fn.startswith("test_"):
                    try:
                        V(rel).visit(ast.parse(open(path, encoding="utf-8").read()))
                    except (SyntaxError, UnicodeDecodeError):
                        pass
                elif fn.endswith((".sh", ".lua", ".conf", ".cf", ".toml")) or fn.startswith("Dockerfile"):
                    txt = open(path, encoding="utf-8", errors="replace").read()
                    for m in shell_re.finditer(txt):
                        add(m.group(1), m.group(2), rel)
    return found


def toml_str(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_str(x) for x in v) + "]"
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def write_catalog(entries: dict[str, dict]) -> None:
    groups: dict[str, list[str]] = {}
    for name, e in entries.items():
        groups.setdefault(e["group"], []).append(name)
    order = ["endpoints", "database", "redis", "secrets", "auth", "sending", "deliverability", "mta",
             "nodes", "events", "observability", "runtime", "storage", "billing", "integrations",
             "removed", "internal", "misc"]
    lines = [
        "# RevBridge Connect — full catalog of environment variables.",
        "# GENERATED by tools/manifest/scan_env.py from the code; entries with curated = true are preserved.",
        "# Whoever runs the installation edits connect.toml, not this file.",
        "#",
        "# status: derive  = computed from connect.toml (the `value` field is a {{key}} template)",
        "#         keep    = inherited default (from the code)",
        "#         secret  = generated by `make env` in secrets/ (never in git)",
        "#         off     = code present, feature turned off in Connect",
        "#         remove  = to be removed from the code",
        "#         internal= local script/test variable, not configuration",
        "#         review  = not classified yet",
        "",
    ]
    for g in order + sorted(set(groups) - set(order)):
        if g not in groups:
            continue
        lines.append(f"# ───────────── {g} ─────────────")
        for name in sorted(groups[g]):
            e = entries[name]
            lines.append(f"[{name}]")
            for k in ("group", "status", "value", "code_default", "services", "note", "curated", "deviation"):
                # value = "" is explicit (e.g. CONNECT_OVERFLOW_RELAY, RELAYHOST): it means "empty in the
                # .env", not "no value"; without this the code's inherited default would apply again
                explicit_empty = k == "value" and e.get(k) == ""
                if k in e and (explicit_empty or e[k] not in (None, "", [], set())):
                    v = sorted(e[k]) if isinstance(e[k], set) else e[k]
                    lines.append(f"{k} = {toml_str(v)}")
            lines.append("")
    os.makedirs(os.path.dirname(CATALOG), exist_ok=True)
    with open(CATALOG, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    found = scan()
    current: dict[str, dict] = {}
    if os.path.exists(CATALOG):
        with open(CATALOG, "rb") as fh:
            current = tomllib.load(fh)

    if args.check:
        missing = sorted(set(found) - set(current))
        if missing:
            print("variables read by the code but missing from the catalog:", ", ".join(missing))
            return 1
        print(f"ok: {len(found)} variables in the code, all in the catalog ({len(current)} entries)")
        return 0

    overrides: dict[str, dict] = {}
    if os.path.exists(OVERRIDES):
        with open(OVERRIDES, "rb") as fh:
            overrides = tomllib.load(fh)

    out: dict[str, dict] = {}
    for name in sorted(set(found) | set(current) | set(overrides)):
        # only what the code reads (or what the curated file declares) goes in
        if name not in found and name not in overrides:
            continue
        old = current.get(name, {})
        f = found.get(name)
        group, status, note = classify(name)
        e = {
            "group": group,
            "status": status,
            "note": note,
            "services": sorted(f["services"]) if f else old.get("services", []),
            "code_default": " | ".join(sorted(f["defaults"]))[:200] if f and f["defaults"] else old.get("code_default"),
        }
        if not f:
            e["note"] = (e["note"] + "; " if e["note"] else "") + "not found in the code; confirm"
        if old.get("curated"):
            for k in ("group", "status", "value", "note", "curated", "deviation"):
                if k in old:
                    e[k] = old[k]
        elif e["status"] == "keep" and "value" in old:
            e["value"] = old["value"]  # keep the value already applied
        if name in overrides:
            e.update(overrides[name])
            e["curated"] = True
        out[name] = e
    write_catalog(out)
    by = {}
    for e in out.values():
        by[e["status"]] = by.get(e["status"], 0) + 1
    print(f"catalog: {len(out)} variables -> {CATALOG}")
    print("by status:", dict(sorted(by.items(), key=lambda x: -x[1])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
