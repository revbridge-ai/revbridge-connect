"""Generates the installation's configuration from connect.toml + config/variables.toml.

Outputs (all 0600, outside git):
- secrets/generated.env  secrets generated ONCE and reused on later runs;
- secrets/env/common.env  configuration without secrets, read by every service;
- secrets/env/<scope>.env  the secrets of each group of services (each container only gets
  those of its scope: the image proxy never sees the database password, the MTA never sees the JWT key…);
- .env  only what docker compose interpolates in docker-compose.yml (MySQL root password for
  the db service, MTA hostname, replicas and workers).

Only variables with an explicit value are written (derive, secret, curated). The others keep
the code's own default. `remove` and `internal` variables are never written.

Usage: python3 scripts/render_env.py [--print]
Standard library only (Python >= 3.11).
"""

from __future__ import annotations

import base64
import os
import re
import secrets
import subprocess
import sys
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
MANIFEST = os.path.join(ROOT, "connect.toml")
CATALOG = os.path.join(ROOT, "config", "variables.toml")
SECRETS = os.path.join(ROOT, "secrets", "generated.env")
ENV_DIR = os.path.join(ROOT, "secrets", "env")
OUT = os.path.join(ROOT, ".env")

GENERATED_SECRETS = {
    "DB_PASSWORD": lambda: secrets.token_urlsafe(24),
    "MYSQL_ROOT_PASSWORD": lambda: secrets.token_urlsafe(24),
    "MTA_DB_PASSWORD": lambda: secrets.token_urlsafe(24),
    "REDIS_PASSWORD": lambda: secrets.token_urlsafe(24),
    # Fernet: 32 bytes in urlsafe base64 (pixel, click and unsubscribe tokens)
    "TOKEN_ENCRYPTION_KEY": lambda: base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
    "JWT_SECRET_KEY": lambda: secrets.token_hex(32),
    "IMAGE_PROXY_SECRET": lambda: secrets.token_urlsafe(32),
}

# Who gets each secret. A catalog variable whose value uses {{secret.X}} only goes to the
# scopes of X. Scopes (docker-compose.yml):
#   app       api, queue-processor, ledger-reaper, webhook-dispatcher, scheduler
#   tracking  tracking
#   events    events, milter
#   mta       mta
#   proxy     image-proxy
SECRET_SCOPES = {
    "DB_PASSWORD": ("app", "tracking", "events"),
    "REDIS_PASSWORD": ("app", "tracking", "events"),
    "TOKEN_ENCRYPTION_KEY": ("app", "tracking", "events"),
    "JWT_SECRET_KEY": ("app",),
    "IMAGE_PROXY_SECRET": ("app", "proxy"),
    "MTA_DB_PASSWORD": ("mta",),
}
SCOPES = ("app", "tracking", "events", "mta", "proxy")

# {{section.key}} or {{section.key:label}} (first label of a hostname: mta1.example.com -> mta1)
TEMPLATE = re.compile(r"\{\{\s*([a-zA-Z0-9_.]+(?::label)?)\s*\}\}")
SECRET_REF = re.compile(r"\{\{\s*secret\.([A-Z0-9_]+)\s*\}\}")


def _write_private(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old_umask = os.umask(0o077)
    try:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    finally:
        os.umask(old_umask)
    os.chmod(path, 0o600)


def load_secrets() -> dict[str, str]:
    values: dict[str, str] = {}
    if os.path.exists(SECRETS):
        for line in open(SECRETS, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                values[k] = v
    changed = False
    for name, gen in GENERATED_SECRETS.items():
        if not values.get(name):
            values[name] = gen()
            changed = True
    if changed:
        _write_private(
            SECRETS,
            "# Generated by scripts/render_env.py. NEVER commit it. Changing TOKEN_ENCRYPTION_KEY invalidates links already sent.\n"
            + "".join(f"{k}={values[k]}\n" for k in sorted(values)),
        )
    return values


def lookup(path: str, manifest: dict, sec: dict[str, str]) -> str:
    if path.endswith(":label"):
        return lookup(path[: -len(":label")], manifest, sec).split(".", 1)[0]
    if path.startswith("secret."):
        key = path.split(".", 1)[1]
        if key not in sec:
            raise SystemExit(f"unknown secret in template: {key}")
        return sec[key]
    cur = manifest
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            raise SystemExit(f"key missing from connect.toml: {path}")
        cur = cur[part]
    return str(cur)


def validate(manifest: dict) -> list[str]:
    warns = []
    inst = manifest.get("install", {})
    if not inst.get("public_ip"):
        warns.append("install.public_ip is empty: fine for local testing, required in production")
    if inst.get("domain", "").endswith("example.com"):
        warns.append("install.domain is still example.com")
    if manifest.get("delivery", {}).get("mode") != "direct":
        raise SystemExit("delivery.mode only accepts 'direct' (Connect does not send through a provider)")
    return warns


def ensure_submission_cert(manifest: dict) -> None:
    """SMTP certificate for local testing. In production the MTA uses the one Caddy issues for
    endpoints.submission (Let's Encrypt); this self-signed one only serves until DNS is in place."""
    tls = os.path.join(ROOT, "secrets", "tls")
    crt, key = os.path.join(tls, "tls.crt"), os.path.join(tls, "tls.key")
    if os.path.exists(crt) and os.path.exists(key):
        return
    os.makedirs(tls, exist_ok=True)
    cn = manifest["endpoints"]["submission"]
    rc = subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "365",
         "-subj", f"/CN={cn}", "-keyout", key, "-out", crt],
        capture_output=True, text=True,
    ).returncode
    if rc != 0:
        raise SystemExit("failed to generate the self-signed certificate (openssl)")
    os.chmod(key, 0o644)  # the MTA container reads it as root; the secrets/ folder stays outside git
    print(f"warning: self-signed certificate generated for {cn} (testing only)", file=sys.stderr)


def main() -> int:
    with open(MANIFEST, "rb") as fh:
        manifest = tomllib.load(fh)
    with open(CATALOG, "rb") as fh:
        catalog = tomllib.load(fh)
    for w in validate(manifest):
        print("warning:", w, file=sys.stderr)
    sec = load_secrets()
    ensure_submission_cert(manifest)

    common: list[str] = [
        f"CONNECT_INSTALL={manifest['install']['name']}",
        f"TZ={manifest['install'].get('timezone', 'UTC')}",
    ]
    scoped: dict[str, list[str]] = {s: [] for s in SCOPES}
    for name in sorted(catalog):
        e = catalog[name]
        if e.get("status") in ("remove", "internal") or "value" not in e:
            continue
        raw = str(e["value"])
        value = TEMPLATE.sub(lambda m: lookup(m.group(1), manifest, sec), raw)
        if "\n" in value:
            raise SystemExit(f"value with a line break in {name}")
        refs = SECRET_REF.findall(raw)
        if not refs:
            common.append(f"{name}={value}")
            continue
        targets = None
        for ref in refs:
            if ref not in SECRET_SCOPES:
                raise SystemExit(f"{name} uses the secret {ref}, which has no scope in SECRET_SCOPES")
            t = set(SECRET_SCOPES[ref])
            targets = t if targets is None else targets & t
        for scope in sorted(targets or ()):
            scoped[scope].append(f"{name}={value}")

    header = "# GENERATED by scripts/render_env.py from connect.toml + config/variables.toml. Do not edit by hand.\n"
    _write_private(os.path.join(ENV_DIR, "common.env"), header + "\n".join(common) + "\n")
    for scope, lines in scoped.items():
        _write_private(os.path.join(ENV_DIR, f"{scope}.env"), header + "\n".join(lines) + ("\n" if lines else ""))

    scale = manifest.get("scale", {})
    compose_env = [
        f"CONNECT_INSTALL={manifest['install']['name']}",
        f"MYHOSTNAME={manifest['install']['hostname']}",
        f"TZ={manifest['install'].get('timezone', 'UTC')}",
        f"MYSQL_ROOT_PASSWORD={sec['MYSQL_ROOT_PASSWORD']}",
        f"MYSQL_DATABASE={manifest['mysql']['database']}",
        f"MYSQL_USER={manifest['mysql']['user']}",
        f"MYSQL_PASSWORD={sec['DB_PASSWORD']}",
        f"MTA_DB_PASSWORD={sec['MTA_DB_PASSWORD']}",
        f"REDIS_PASSWORD={sec['REDIS_PASSWORD']}",
        f"QUEUE_PROCESSOR_REPLICAS={int(scale.get('queue_processors', 8))}",
        f"API_WORKERS={int(scale.get('api_workers', 2))}",
        f"TRACKING_WORKERS={int(scale.get('tracking_workers', 2))}",
        f"EVENTS_WORKERS={int(scale.get('events_workers', 2))}",
    ]
    _write_private(
        OUT,
        "# GENERATED by scripts/render_env.py: only what docker compose interpolates. Do not edit by hand.\n"
        + "\n".join(compose_env) + "\n",
    )

    # Copy of the manifest for the containers (mounted as a folder: a single-file bind mount
    # loses track of the file when it is rewritten on the host).
    gen = os.path.join(ROOT, "config", "generated")
    os.makedirs(gen, exist_ok=True)
    with open(MANIFEST, "rb") as src, open(os.path.join(gen, "connect.toml"), "wb") as dst:
        dst.write(src.read())

    if "--print" in sys.argv:
        for ln in common:
            print(ln)
        for scope, lines in scoped.items():
            for ln in lines:
                print(f"[{scope}] {ln.split('=', 1)[0]}=<secret>")
    total = len(common) + sum(len(v) for v in scoped.values())
    print(f"config: {len(common)} common variables + {total - len(common)} per-scope secrets -> secrets/env/; compose .env -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
